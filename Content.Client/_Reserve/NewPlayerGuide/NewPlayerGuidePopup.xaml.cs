using System.Linq;
using Content.Client.Guidebook;
using Content.Client.Guidebook.Richtext;
using Content.Shared._Reserve.NewPlayerGuide;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.ContentPack;
using Robust.Shared.Prototypes;

namespace Content.Client._Reserve.NewPlayerGuide;

[GenerateTypedNameReferences]
public sealed partial class NewPlayerGuidePopup : Control, INewPlayerGuideHost
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IResourceManager _resourceManager = default!;
    [Dependency] private readonly DocumentParsingManager _parsingMan = default!;
    [Dependency] private readonly GuidebookLocalizationManager _localization = default!;

    private readonly ISawmill _sawmill;
    private readonly List<NewPlayerGuidePagePrototype> _pages;

    private int _pageIndex;
    private bool _showRulesAfter = true;

    /// <summary>
    ///     Whether the player changed any of the game settings offered by the guide.
    ///     Used to avoid needlessly writing out the client config.
    /// </summary>
    public bool SettingsChanged { get; private set; }

    public int PageCount => _pages.Count;
    public int CurrentPageIndex => _pageIndex;

    /// <summary>
    ///     Whether the server rules should be shown once the guide is dismissed.
    /// </summary>
    public bool ShowRulesAfter
    {
        get => _showRulesAfter;
        set
        {
            _showRulesAfter = value;
            if (_pages.Count == 0 || _pageIndex == _pages.Count - 1)
                UpdateNextButton();
        }
    }

    public event Action? OnClosed;

    public NewPlayerGuidePopup()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = Logger.GetSawmill("newplayerguide");

        TitleLabel.Text = Loc.GetString("new-player-guide-title");
        SubtitleLabel.Text = Loc.GetString("new-player-guide-subtitle");

        _pages = _prototype.EnumeratePrototypes<NewPlayerGuidePagePrototype>()
            .OrderBy(p => p.Order)
            .ThenBy(p => p.ID, StringComparer.Ordinal)
            .ToList();

        SkipButton.OnPressed += _ => OnClosed?.Invoke();
        BackButton.OnPressed += _ => ShowPage(_pageIndex - 1);
        NextButton.OnPressed += _ => OnNextPressed();

        if (_pages.Count > 0)
        {
            ShowPage(0);
        }
        else
        {
            PageCounterLabel.Text = string.Empty;
            BackButton.Disabled = true;
            SkipButton.Visible = false;
            UpdateNextButton();
        }
    }

    public void NotifySettingChanged()
    {
        SettingsChanged = true;
    }

    private void OnNextPressed()
    {
        if (_pages.Count == 0 || _pageIndex >= _pages.Count - 1)
        {
            OnClosed?.Invoke();
            return;
        }

        ShowPage(_pageIndex + 1);
    }

    public void ShowPage(int index)
    {
        if (index < 0 || index >= _pages.Count)
            return;

        _pageIndex = index;

        PageContainer.DisposeAllChildren();

        var page = _pages[index];
        var path = page.GetLocalizedDocumentPath(_localization.GetCurrentCultureName());

        if (path == default || !_resourceManager.ContentFileExists(path))
        {
            _sawmill.Error($"NewPlayerGuide page {page.ID} has missing document path: {path}");
        }
        else
        {
            using var file = _resourceManager.ContentFileReadText(path);
            var text = file.ReadToEnd();

            if (!_parsingMan.TryAddMarkup(PageContainer, text))
                _sawmill.Error($"Failed to parse contents of NewPlayerGuide page {page.ID} ({path}).");

            foreach (var child in PageContainer.Children)
            {
                if (child is Document doc)
                {
                    doc.HorizontalExpand = true;
                    doc.SeparationOverride ??= 8;
                }
            }
        }

        PageCounterLabel.Text = Loc.GetString("new-player-guide-page-counter",
            ("current", index + 1),
            ("total", _pages.Count));

        BackButton.Disabled = index == 0;
        SkipButton.Visible = index != _pages.Count - 1;
        UpdateNextButton();

        Scroll.SetScrollValue(default);
    }

    private void UpdateNextButton()
    {
        var isLastPage = _pages.Count == 0 || _pageIndex >= _pages.Count - 1;

        NextButton.Text = Loc.GetString(!isLastPage
            ? "new-player-guide-next"
            : _showRulesAfter
                ? "new-player-guide-finish"
                : "new-player-guide-close");
    }
}
